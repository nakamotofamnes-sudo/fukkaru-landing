def extract_json(s: str) -> dict:
    """```json ...``` で囲まれていても中身を取り出す。"""
    s = s.strip()
    m = re.search(r"```(?:json)?\s*(.+?)\s*```", s, re.S)
    if m:
        s = m.group(1)
    start, end = s.find("{"), s.rfind("}")
    if start < 0 or end < 0:
        raise ValueError("JSONが見つかりません：" + s[:200])
    return json.loads(s[start:end + 1])


