def seikei(art: dict) -> int:
    """記事の段落を整える。直した数を返す。**文字は変えない**"""
    blocks = art.get("blocks")
    if not isinstance(blocks, list):
        return 0
    naoshita, atarashii = 0, []

    # slug は弾かずに直す（ō などの伸ばす記号を落とす）
    if isinstance(art.get("slug"), str):
        naoshi = slug_naosu(art["slug"])
        if naoshi and naoshi != art["slug"]:
            art["slug"] = naoshi; naoshita += 1

    # **まずタグを直す。**そのあとで段落を分ける（<br> が改行になってから分けたい）
    for b in blocks:
        if not isinstance(b, dict):
            continue
        for k in ("text", "title"):
            if isinstance(b.get(k), str):
                naoshi = tag_naosu(b[k])
                if naoshi != b[k]:
                    b[k] = naoshi; naoshita += 1
        if isinstance(b.get("items"), list):
            # **箇条書きの中も数える。**数えないと「直していない」ことになり、
            # 書き込みが飛ばされます（2026-09-12、実際にそうなりました）
            mae = list(b["items"])
            b["items"] = [tag_naosu(x) if isinstance(x, str) else x for x in b["items"]]
            if b["items"] != mae:
                naoshita += 1

    for b in blocks:
        # ── 段落を整える（2026-09-13 に組み直しました）──
        #
        # **通り道は1本だけにします。**
        # それまでは「空行で分けたかけら」が直しを通らずにそのまま並んでいて、
        # かけらの中に見出しや箇条書きが残ると、弁が弾き続けていました。
        # 2026-09-13の16時、**4回試して1本も出せず、記事が落ちました。**
        #
        #   空行で分ける → 見出し・箇条書きを外に出す → 長さとリズムで分ける
        #
        # lead も同じ道を通します（先頭だけ lead のまま）。
        if not isinstance(b, dict) or b.get("type") not in ("p", "lead"):
            atarashii.append(b); continue
        t = str(b.get("text", ""))
        kire = [x.strip() for x in re.split(r"\n\s*\n", t) if x.strip()] or [t]
        dekita = []
        for i, x in enumerate(kire):
            dekita += _p_naosu(x, b["type"] if i == 0 else "p")
        if dekita and dekita != [b]:
            atarashii += dekita; naoshita += 1
        else:
            atarashii.append(b)
    # ── 2026-09-14 に足した直し（どれも弾かずに直す）──
    # 一覧の崩れは、空行で分けたあとに見る（分けたせいで1行ずつの段落になるため）
    atarashii, n = ichiran_naosu(atarashii)
    naoshita += n
    for b in atarashii:
        naoshita += kajo_naosu(b)
    atarashii, n = hoshi_naosu(atarashii)
    naoshita += n
    atarashii, n = kyoka_naosu(art, atarashii)
    naoshita += n
    atarashii, n = nai_naosu(art, atarashii)
    naoshita += n
    atarashii, n = kotowari_naosu(art, atarashii)
    naoshita += n
    atarashii, n = renzoku_naosu(atarashii)
    naoshita += n
    if naoshita:
        art["blocks"] = atarashii
    return naoshita


def check(art: dict, done: list[dict], attempt: int = 1, last: int = 1) -> list[str]:
    """出せる形になっているか調べる。戻り値は問題点の一覧（空なら合格）。"""
    ng = []
    for k in ("slug", "title", "metaDescription", "keywords", "category", "blocks"):
        if not art.get(k):
            ng.append("%s がありません" % k)
    slug = str(art.get("slug", ""))
    if not re.fullmatch(r"[a-z0-9-]+", slug):
        ng.append("slug に使えない文字があります：%s" % slug)
    if slug in {a.get("slug") for a in done}:
        ng.append("slug が既存記事と同じです：%s" % slug)
    if (ARTICLES / f"{slug}.json").exists():
        ng.append("同じ名前のファイルが既にあります：%s.json" % slug)

    # ── 段落の設計を弾く（2026-09-12）──
    #
    # **中元さんの指摘：「文章はしっかりしているけど設計がダメ」。そのとおりだった。**
    # 実測（記事27本・段落268個）：**300字超が24個、いちばん長いもので1,410字。**
    # 1つの段落の中に見出しと箇条書きが詰め込まれていた。
    #
    # **原因は私です。**2026-09-10に「1つの p は必ず200字以上」と
    # **下限だけ**指定し、上限を書かなかった。
    #
    # 参考にした実測：よく読まれているブログ（manablog）は
    # **段落の平均54〜68字・最長168字・60字未満が半分。**
    # フッ軽は平均168字・最長1,410字だった。
    #
    # **境目は指示より緩くしてあります**（指示300字／弾くのは400字から）。
    # ぴったり守らせると作り直しが増える。**作り直しがいちばん高い。**
    P_MAX = int(os.environ.get("FUKKARU_P_MAX") or 400)
    for i, b in enumerate(art.get("blocks") or []):
        if b.get("type") != "p":
            continue
        t = str(b.get("text", ""))
        if len(t) > P_MAX:
            ng.append("%d番目の段落が長すぎます（%d字／%d字まで）。"
                      "そこで段落を分けてください" % (i + 1, len(t), P_MAX))
        # **ここは最後の網です。**ふつうは seikei() が先に直すので、鳴りません。
        # 鳴ったら「自動で直しきれなかった」という意味なので、そのときは直し方を見直す
        if p_kuzure(t):
            # **どの行が引っかかったかを出す。**
            # 2026-09-13、文面が分からず原因の当てが外れました
            warui = [x.strip() for x in t.split("\n") if p_kuzure(x)]
            if warui:
                ng.append("段落の中に見出しか箇条書きが混ざっています（%d番目・「%s」）。"
                          "**見出しは h3、箇条書きは ul か ol のブロックに分けてください**"
                          % (i + 1, warui[0][:30]))
                continue
            ng.append("%d番目の段落の中に、見出しか箇条書きが混ざっています。"
                      "**見出しは h3、箇条書きは ul か ol のブロックに分けてください**"
                      % (i + 1))

    # ── 他社・比較サイトの名前を弾く（2026-09-11、中元さんの判断）──
    # **指示に書くだけでは守らないことがあるので、出来上がりを見て弾きます。**
    # 名前を出すと、お客様がそちら経由で依頼するようになり手数料がかかる。
    # （ニトリ・IKEA・イナバなど「組み立てる品物のメーカー名」は別。これは書いてよい）
    tasha = ("くらしのマーケット", "くらマ", "curama", "ミツモア", "ジモティー",
             "ユアマイスター", "ココナラ")
    blob_all = json.dumps(art, ensure_ascii=False)
    hit = [t for t in tasha if t in blob_all]
    if hit:
        ng.append("他社・比較サイトの名前が入っています：%s（記事に書かないでください）"
                  % "、".join(hit))

    blocks = art.get("blocks") or []
    types = {b.get("type") for b in blocks if isinstance(b, dict)}
    unknown = types - BLOCK_TYPES
    if unknown:
        ng.append("使えない種類のブロックがあります：%s" % ", ".join(sorted(map(str, unknown))))
    # h3 と ul を足した（2026-09-12）。
    # **実測：いまの記事27本のうち6本が、h3 か ul のどちらかを持っていない。**
    # （「26本が持っている」と書きかけたが、数えたら違った。**数えてから書くこと**）
    # 6本なので、作り直しが増えるのは 6/27 の見込み。
    # **箇条書きも小見出しも無い記事は、文字の壁になる**ので、そこは受け入れる
    # **最後の1回は、h3 と ul が無いだけでは弾かない**（2026-09-14、中元さん「毎日の記事は必ず投稿に」）。
    # 文字の壁は困るが、記事がゼロになるよりはまし。lead・h2・p・cta は最後まで見る
    hitsuyou = ("lead", "h2", "h3", "p", "ul", "cta") if attempt < last else ("lead", "h2", "p", "cta")
    for need in hitsuyou:
        if need not in types:
            ng.append("%s ブロックがありません" % need)
    for b in blocks:
        if isinstance(b, dict) and b.get("type") == "h2" and not b.get("id"):
            ng.append("h2 に id が付いていません：%s" % b.get("text", "")[:20])

    body = "".join((b.get("text") or "") for b in blocks if isinstance(b, dict))
    # 最後の1回だけ、下限を1,000字まで下げる（同じ理由。数字・許認可・名前の弁は下げない）
    saitei = MIN_BODY if attempt < last else 1000
    if len(body) < saitei:
        ng.append("本文が短すぎます（%d字／最低%d字）" % (len(body), saitei))

    whole = json.dumps(art, ensure_ascii=False)

    # 実在しない名前で名乗らせない（2026-09-08 に追加）。
    # 2026-09-07、SNSの投稿が「代表のコバヤシです」で出た。以前は「ナカジマ」も。
    # **どちらも実在しない。**名前を教えていなかったので、AIが作っていた。
    # 指示に足すだけでは足りないので、出来上がりからも見る。
    # 2026-09-14 に狭めた（弁は外していない）：「代表の方が一人で…」「代表の経験に基づいて」を
    # 名前と取り違えて、作り直しを弾いていた。名前ではない言葉で始まるものは見ない
    HITO_DENAI = ("中元", "なかもと", "ナカモト", "私", "方", "者", "人", "経験", "考え",
                  "強み", "立場", "判断", "目線", "視点", "責任", "知識", "仕事", "手", "目")
    for m in re.finditer(r"代表の([ぁ-んァ-ヶー一-龥A-Za-z]{2,6})", whole):
        who = m.group(1)
        if not any(who.startswith(ok) for ok in HITO_DENAI):
            ng.append("実在しない名前を名乗っています：「代表の%s」"
                      "（フッ軽の代表は中元です。迷うなら『代表の私が』）" % who)

    # 廃棄物の許可が無いのに「処分を請け負う」と読める書き方をさせない
    # **言い回しの一覧は KYOKA_KINSHI の1か所。**seikei() が先にその文を外すので、ふつうは鳴らない
    for w in KYOKA_KINSHI:
        if w in whole:
            ng.append("ごみの処分を請け負う書き方です（一般廃棄物の許可が無い）：%s" % w)

    # 自社を主語にして「回収」「引き取り」を約束させない（2026-09-04 に追加）。
    # 上の弁は決まり文句だけを見ていたので、
    # 「不用な梱包材の回収、古い家具の引き取りまでまとめてお任せいただけます」を
    # 素通りさせ、本番に1本出てしまった。文の形で見る。
    # 判定は kyoka_yakusoku() の1か所（seikei() の直しと同じもの）
    for t in (b.get("text") or "" for b in blocks if isinstance(b, dict)):
        for sent in re.split(r"(?<=[。！？])", t):
            riyuu = kyoka_yakusoku(sent)
            if riyuu:
                ng.append("%s：%s" % (riyuu, sent.strip()[:50]))

    # 許認可の誤認よけ。「無許可の業者」の話のすぐ後に自社名を出させない
    for b in blocks:
        if not isinstance(b, dict):
            continue
        t = (b.get("text") or "") + (b.get("title") or "")
        if ("無許可" in t or "許可を得ず" in t) and "フッ軽" in t:
            ng.append("無許可業者の話と自社の宣伝が同じ塊にあります（許可の誤認を招く）")

    # タイトルの型が既存とかぶっていないか。
    # **最後の1回だけは見送ります。**ここで粘ると、その日の記事がゼロになります
    # （2026-09-02、別の弁で実際に1本飛びました）。見た目の重複より、記事が出るほうが大事です。
    if attempt < last:
        clash = title_clash(str(art.get("title", "")), done)
        if clash:
            ng.append("タイトルの型が既存記事とかぶっています（地名だけ変えたように見えます）："
                      "%s ←ここと似すぎ" % clash[1])
        # 説明文（検索結果に出る2〜3行）も同じ理由で見る。
        # 実測（既存15本の総当たり105組）でかぶっていたのは1組だけなので、
        # ここを厳しくしても記事が書けなくなる心配は薄い。
        md = str(art.get("metaDescription", ""))
        shape = title_shape(md)
        if shape:
            import difflib
            for a in done:
                r = difflib.SequenceMatcher(
                    None, shape, title_shape(a.get("metaDescription", ""))).ratio()
                if r >= TITLE_SHAPE_MAX:
                    ng.append("説明文の型が既存記事とかぶっています：%s ←ここと似すぎ"
                              % a.get("title", ""))
                    break

    # 数字の捏造よけ。実績値を書かせない約束なので、見つけたら止める。
    # ただし、サイトに載っている料金と同じ額は通す（捏造ではなく会社の事実のため）。
    #
    # **「1件」「1人」「1台」は通します**（2026-09-24 に狭めました）。
    # この弁が止めたいのは「施工実績500件」「満足度98%」のような**盛った実績**です。
    # **1は、盛れません。**その日の16時の記事は「1台」ひとつで4回とも落ち、
    # **1本も出ませんでした。**円と割は通しません（金額と値引き率になるため）。
    allowed = set(KNOWN_NUMBERS) | set(FUJI_CITY_FEES) | site_prices()
    found = {m.group(0) for m in NUM.finditer(json.dumps(art, ensure_ascii=False))}
    hits = sorted(h for h in found
                  if h.replace(" ", "") not in allowed
                  and not re.fullmatch(r"1\s*(?:件|人|台)", h))
    if hits:
        ng.append("数値が書かれています（サイトに載っていない数字は書けません）：%s"
                  % ", ".join(hits[:6]))
    return ng


# gitは -C でリポジトリを指しても、動き出す前に自分の居場所を一度読む。
# launchd から走ると居場所が読めない場所のことがあり、
# 「Unable to read current working directory: Operation not permitted」で落ちる。
# 居場所をリポジトリ自身に固定しておく。
def git(*args: str) -> str:
    r = subprocess.run(["git", "-C", str(REPO), *args],
                       capture_output=True, text=True, cwd=str(REPO))
    if r.returncode != 0:
        raise RuntimeError("git %s -> %s" % (" ".join(args), r.stderr.strip()[:300]))
    return r.stdout.strip()


def git_ok(*args: str) -> bool:
    """成否だけ知りたいとき（失敗しても例外にしない）"""
    return subprocess.run(["git", "-C", str(REPO), *args],
                          capture_output=True, text=True,
                          cwd=str(REPO)).returncode == 0


def gh_api(path: str, data: dict | None = None, method: str = "GET") -> dict:
    req = urllib.request.Request(
        "https://api.github.com/repos/%s/%s%s" % (GH_OWNER, GH_REPO, path),
        data=json.dumps(data).encode("utf-8") if data else None,
        method=method,
        headers={"Authorization": "Bearer " + GH_PAT,
                 "Accept": "application/vnd.github+json",
                 "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read().decode("utf-8"))


