# **言っても直らないものは、こちらで直す。**作り直しは1本7,167トークンかかります。
#
# やること2つ（**文字は1文字も足さない・消さない**）：
#   ① p の中の「太字だけの行」を h3 に、「・」「*」「1.」の行を ul に分ける
#   ② p を「。」の切れ目で、1〜2文・100字くらいに分ける（2026-09-14 に基準を変えた）
