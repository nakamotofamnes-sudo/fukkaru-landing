def log(msg: str) -> None:
    LOGF.parent.mkdir(parents=True, exist_ok=True)
    line = "[%s] %s" % (date.today().strftime("%Y-%m-%d"), msg)
    print(line)
    with LOGF.open("a", encoding="utf-8") as f:
        f.write(line + "\n")


