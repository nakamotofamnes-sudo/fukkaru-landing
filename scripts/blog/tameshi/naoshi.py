NG = 0


def kazoeru(label, chigai):
    """chigai … ちがったものの一覧（文字の一覧）"""
    global NG
    NG += len(chigai)
    print(('○ ' if not chigai else '✗ ') + label + ('' if not chigai else '／ちがったもの %d' % len(chigai)))
    for c in chigai:
        print('     ✗', c)


def onaji(label, got, want):
    kazoeru(label, [] if got == want else ['出た: %r ／ 望み: %r' % (got, want)])


